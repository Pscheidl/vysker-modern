test('submission locks all selection and personal fields until a failed request finishes', async ({ page }) => {
  let releaseRequest!: () => void
  let markRequestSeen!: () => void
  const requestSeen = new Promise<void>(resolve => { markRequestSeen = resolve })
  const requestGate = new Promise<void>(resolve => { releaseRequest = resolve })
  await page.route('**/api/v1/rentals', async route => {
    markRequestSeen()
    await requestGate
    await route.fulfill({ status: 503, json: { error: 'Zkušební chyba odeslání.' } })
  })
  await calendarPage(page)
  await page.locator('#rental-calendar [data-date="2030-06-04"]').click()
  await page.locator('#rental-hours [data-start-minute="600"]').click()
  await page.getByLabel('Jméno a příjmení', { exact: true }).fill('Jan Novák')
  await page.getByRole('combobox', { name: 'Adresa', exact: true }).fill('Vyskeř 50')
  await page.getByLabel('E-mail', { exact: true }).fill('jan@example.test')
  await page.getByLabel('Telefon', { exact: true }).fill('+420 777 123 456')
  await page.getByLabel('Kopie občanského průkazu', { exact: true }).setInputFiles('public/images/vysker-znak-app-192.png')
  await page.getByLabel('Souhlasím s dočasným uložením').check()
  await page.getByRole('button', { name: 'Odeslat žádost' }).click()
  try {
    await requestSeen
    for (const selector of ['#rental-asset', '#rental-event-type', '#rental-mode-hour', '#rental-mode-day',
      '#rental-start', '#rental-end', '#rental-start-time', '#rental-end-time', '#rental-tenant-type']) {
      await expect(page.locator(selector)).toBeDisabled()
    }
    await expect(page.locator('#rental-calendar [data-date="2030-06-05"]')).toBeDisabled()
    await expect(page.locator('#rental-hours [data-start-minute="660"]')).toBeDisabled()
    await expect(page.getByLabel('Jméno a příjmení', { exact: true })).toBeDisabled()
    await expect(page.getByRole('combobox', { name: 'Adresa', exact: true })).toBeDisabled()
  } finally {
    releaseRequest()
  }
  await expect(page.locator('#rental-message')).toContainText('Zkušební chyba odeslání.')
  await expect(page.locator('#rental-start')).toBeEnabled()
  await expect(page.locator('#rental-event-type')).toBeEnabled()
  await expect(page.locator('#rental-mode-day')).toBeEnabled()
  await expect(page.getByLabel('Jméno a příjmení', { exact: true })).toBeEnabled()
  await expect(page.locator('#rental-start')).toHaveValue('2030-06-04')
  await expect(page.locator('#rental-start-time')).toHaveValue('10:00')
  await expect(page.locator('#rental-end-time')).toHaveValue('11:00')
})

