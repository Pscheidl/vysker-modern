test('periodic refresh preserves focus without scrolling the page', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 600 })
  await calendarPage(page, '2030-06-03T12:00:00Z', 'červen 2030', true)
  await page.addStyleTag({ content: 'html { scroll-behavior: auto !important; }' })
  const day = page.locator('#rental-calendar [data-date="2030-06-04"]')
  await day.focus()
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await page.clock.fastForward(30_000)
  await expect(day).toBeFocused()
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await day.click()
  const slot = page.locator('#rental-hours [data-start-minute="600"]')
  await slot.focus()
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await page.clock.fastForward(30_000)
  await expect(slot).toBeFocused()
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
})

