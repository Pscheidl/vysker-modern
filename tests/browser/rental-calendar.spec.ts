import { test, expect, type Page } from './fixtures'

test.use({ timezoneId: 'Europe/Prague' })

async function calendarPage(page: Page, now = '2030-06-03T12:00:00Z', month = 'červen 2030', tickingClock = false) {
  if (tickingClock) await page.clock.install({ time: new Date(now) })
  else await page.clock.setFixedTime(new Date(now))
  await page.route('**/api/v1/rental-assets', route => route.fulfill({ json: [
    { id: 1, name: 'Sál', description: 'Zkušební sál', rates: {
      nonprofit: { hourly_price: 0, weekend_day_price: 0 },
      standard: { hourly_price: 30, weekend_day_price: 150 },
    } },
    { id: 2, name: 'Park', description: 'Zkušební park', rates: {
      nonprofit: { hourly_price: null, weekend_day_price: 0 },
      standard: { hourly_price: null, weekend_day_price: 80 },
    } },
  ] }))
  await page.route('**/api/v1/rental-assets/1/availability', route => route.fulfill({ json: [
    { start_date: '2030-06-11', end_date: '2030-06-11', status: 'pending' },
    { start_date: '2030-06-13', end_date: '2030-06-13', status: 'booked' },
    { start_date: '2030-06-17', end_date: '2030-06-17', status: 'booked' },
    { start_date: '2030-06-20', end_date: '2030-06-20', start_time: '10:00', end_time: '12:00', status: 'booked' },
    { start_date: '2030-06-24', end_date: '2030-06-24', start_time: '10:00', end_time: '12:00', status: 'pending' },
    { start_date: '2030-06-25', end_date: '2030-06-25', start_time: '10:00', end_time: '12:00', status: 'pending' },
    { start_date: '2030-06-25', end_date: '2030-06-25', start_time: '14:00', end_time: '16:00', status: 'booked' },
    { start_date: '2030-06-29', end_date: '2030-06-29', status: 'booked' },
  ] }))
  await page.route('**/api/v1/rental-assets/2/availability', route => route.fulfill({ json: [] }))
  await page.goto('/pronajmy')
  await expect(page.locator('#rental-fields')).toBeEnabled()
  await page.locator('#rental-event-type').selectOption('standard')
  await expect(page.locator('#rental-month')).toHaveText(month)
}

test('calendar distinguishes pending dates from occupied dates', async ({ page }) => {
  await calendarPage(page)
  const day = (date: string) => page.locator(`#rental-calendar [data-date="${date}"]`)
  const pending = day('2030-06-11')
  const booked = day('2030-06-13')
  const occupied = day('2030-06-17')
  await expect(pending).toHaveAccessibleName(/žádost čeká na schválení/)
  await expect(booked).toHaveAccessibleName(/obsazeno/)
  await expect(occupied).toHaveAccessibleName(/obsazeno/)
  await expect(pending).toBeDisabled()
  await expect(booked).toBeDisabled()
  await expect(occupied).toBeDisabled()
  await expect(day('2030-06-29')).toBeDisabled()
  await expect(day('2030-06-30')).toBeEnabled()
  const pendingColor = await pending.locator('..').evaluate(cell => getComputedStyle(cell).backgroundColor)
  const bookedColor = await booked.locator('..').evaluate(cell => getComputedStyle(cell).backgroundColor)
  expect(pendingColor).not.toBe(bookedColor)
  await expect(page.getByText(/dostupnost se při odeslání znovu ověří/i)).toHaveCount(0)
})

