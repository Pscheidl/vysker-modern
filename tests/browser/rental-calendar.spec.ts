test('stale hour buttons and a focused native time menu cannot keep an expired start valid', async ({ page }) => {
  let submitted = 0
  await page.route('**/api/v1/rentals', route => { submitted++; return route.fulfill({ status: 201, json: { id: 1 } }) })
  await calendarPage(page, '2030-06-03T12:59:59Z')
  await page.locator('#rental-calendar [data-date="2030-06-03"]').click()
  const startTime = page.locator('#rental-start-time')
  const endTime = page.locator('#rental-end-time')
  const hour = page.locator('#rental-hours [data-start-minute="900"]')
  await expect(hour).toBeEnabled()
  await page.clock.setFixedTime(new Date('2030-06-03T13:00:00Z'))
  // No timer or focus event has redrawn the button yet. Its click must revalidate time.
  await hour.click()
  await expect(hour).toBeDisabled()
  await expect(startTime).toHaveValue('')
  await expect(endTime).toHaveValue('')
  await page.locator('#rental-hours [data-start-minute="960"]').click()
  await expect(startTime).toHaveValue('16:00')
  const submit = page.getByRole('button', { name: 'Odeslat žádost' })
  await expect(submit).toBeEnabled()
  await startTime.focus()
  await page.clock.setFixedTime(new Date('2030-06-03T14:00:00Z'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(startTime).toBeFocused()
  await expect(page.locator('#rental-start-time option[value="16:00"]')).toHaveJSProperty('disabled', true)
  await expect(submit).toBeDisabled()
  await page.locator('#rental-form').dispatchEvent('submit')
  expect(submitted).toBe(0)
  await page.locator('#rental-name').focus()
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(startTime).toHaveValue('')
  await expect(endTime).toHaveValue('')
})

