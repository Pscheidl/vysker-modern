import { test, expect } from './fixtures'

test('the editor inserts a relief into a page and keeps examples literal', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/admin')
  await page.getByLabel('E-mail', { exact: true }).fill('e2e-admin@vysker.test')
  await page.getByLabel('Heslo', { exact: true }).fill('Disposable-browser-test-password!')
  await page.getByRole('button', { name: 'Přihlásit se', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Administrace' })).toBeVisible()
  await page.goto('/admin/stranky/nove')
  await page.getByLabel('Název', { exact: false }).fill('Zkušební reliéf')
  await page.getByLabel('Adresa stránky', { exact: false }).fill('browser-relief')
  const content = page.getByLabel('Obsah stránky', { exact: false })
  await content.fill('Úvodní text')
  await content.evaluate((element: HTMLTextAreaElement) => { element.focus(); element.setSelectionRange(0, element.value.length) })
  await page.getByRole('button', { name: 'Vložit 3D reliéf', exact: true }).click()
  await expect(content).toHaveValue('Úvodní text\n\n{{relief}}\n\n')
  await content.fill('Úvodní text\n\n{{relief}}\n\nPříklad: `{{relief}}`')
  await page.getByRole('button', { name: 'Náhled textu', exact: true }).click()
  const preview = page.getByRole('region', { name: 'Náhled textu stránky' })
  await expect(preview).toContainText('Na stránce se zde zobrazí interaktivní model')
  await expect(preview.locator('code')).toHaveText('{{relief}}')
  await page.getByLabel('Zveřejnit na webu', { exact: false }).check()
  await page.getByRole('button', { name: 'Uložit změny', exact: true }).click()
  await expect(page.getByText('Verze 1', { exact: false })).toBeVisible()
  const response = await request.get('/stranky/browser-relief')
  expect(response.status()).toBe(200)
  const html = await response.text()
  expect(html).toContain('data-relief=')
  expect(html).toContain('Úvodní text')
  await page.goto('/stranky/browser-relief')
  await expect(page.locator('[data-relief]')).toBeVisible()
  await expect(page.locator('.markdown-content code')).toHaveText('{{relief}}')
  await expect(page.locator('#relief-viewport canvas')).toBeVisible({ timeout: 30_000 })
  await expect(page.getByRole('button', { name: 'Celý pohled' })).toBeVisible()
  await page.locator('.relief-places').getByRole('button', { name: 'Drahoňovice' }).click()
  await expect(page.locator('#relief-info-name')).toHaveText('Drahoňovice')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.goto('/relief')
  await expect(page.locator('#relief-viewport canvas')).toBeVisible({ timeout: 30_000 })
  await expect(page.locator('.relief-details')).not.toContainText('Podoba památek vychází z')
  expect(errors).toEqual([])
})
