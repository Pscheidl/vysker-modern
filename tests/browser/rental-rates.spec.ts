import { test, expect } from './fixtures'

test('the two event price groups distinguish a free price from an unset price', async ({ page }) => {
  const screenshotStyle = '.site-header, .skip-link { visibility: hidden !important; }'
  await page.goto('/admin')
  await page.getByLabel('E-mail', { exact: true }).fill('e2e-admin@vysker.test')
  await page.getByLabel('Heslo', { exact: true }).fill('Disposable-browser-test-password!')
  await page.getByRole('button', { name: 'Přihlásit se', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Administrace' })).toBeVisible()
  await page.goto('/admin/pronajmy/majetek')
  await page.getByRole('button', { name: 'Přidat majetek', exact: true }).click()
  const form = page.locator('section.rental-asset-card').filter({ has: page.getByRole('heading', { name: 'Nový majetek', exact: true }) })
  const assetName = `Test ceníku ${Date.now()}`
  await form.getByLabel('Název', { exact: true }).fill(assetName)
  await form.getByLabel('E-mail pro upozornění').fill('office@vysker.test')
  await form.getByLabel('Veřejně prospěšné neziskové akce: cena za hodinu v Kč').fill('0')
  await form.getByLabel('Soukromá akce: cena za hodinu v Kč').fill('200')
  await form.getByLabel('Soukromá akce: cena za den v Kč').fill('250')
  await form.locator('.rental-asset-rates').screenshot({ path: 'target/rental-pricing-admin-desktop.png', style: screenshotStyle })
  const saved = page.waitForResponse(response => response.url().endsWith('/api/v1/admin/rental-assets') && response.request().method() === 'POST')
  await form.getByRole('button', { name: 'Uložit', exact: true }).click()
  const response = await saved
  expect(response.status()).toBe(200)
  const asset = await response.json()
  expect(asset.rates).toEqual({
    nonprofit: { hourly_price: 0, weekend_day_price: null },
    standard: { hourly_price: 200, weekend_day_price: 250 },
  })
  await page.reload()
  const savedCard = page.locator('section.rental-asset-card').filter({ has: page.getByRole('heading', { name: assetName, exact: true }) })
  await expect(savedCard.getByLabel('Veřejně prospěšné neziskové akce: cena za hodinu v Kč')).toHaveValue('0')
  await expect(savedCard.getByLabel('Veřejně prospěšné neziskové akce: cena za den v Kč')).toHaveValue('')
  const publicAssets = await (await page.request.get('/api/v1/rental-assets')).json()
  expect(publicAssets.find((item: { id: number }) => item.id === asset.id).rates).toEqual(asset.rates)

  await page.goto('/pronajmy')
  await page.getByLabel('Co si chcete pronajmout').selectOption({ label: assetName })
  await expect(page.locator('#rental-fields')).toBeEnabled()
  const future = new Date(Date.now() + 14 * 86_400_000)
  future.setUTCDate(future.getUTCDate() + (6 - future.getUTCDay() + 7) % 7)
  const key = future.toISOString().slice(0, 10)
  const weekday = new Date(future.getTime() - 5 * 86_400_000).toISOString().slice(0, 10)
  await page.locator('#rental-event-type').selectOption('nonprofit')
  await expect(page.locator('#rental-mode-day')).toBeDisabled()
  await page.locator('#rental-start').fill(weekday)
  await page.locator('#rental-start-time').selectOption('10:00')
  await page.locator('#rental-end-time').selectOption('11:00')
  await expect(page.locator('#rental-selection-summary')).toContainText('0 Kč')
  await page.locator('#rental-event-type').selectOption('standard')
  await expect(page.locator('#rental-selection-summary')).toContainText('200 Kč')
  await page.locator('#rental-start').fill(key)
  await expect(page.locator('#rental-selection-summary')).toContainText('250 Kč')
  await page.locator('#rental-event-type').selectOption('nonprofit')
  await expect(page.locator('#rental-start')).toHaveValue('')
  await expect(page.locator('#rental-mode-hour')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#rental-mode-day')).toBeDisabled()
  const unavailable = page.locator(`#rental-calendar [data-date="${key}"]`)
  await expect(unavailable).toBeDisabled()
  await expect(unavailable).toHaveAccessibleName(/cena pro tento typ akce není nastavena/)
  await page.locator('#rental-tenant-type').selectOption('organization')
  await page.getByLabel('Název firmy nebo organizace').fill('Testovací spolek')
  await page.getByLabel('IČO', { exact: true }).fill('12345679')
  await page.getByLabel('Jméno a příjmení odpovědné osoby').fill('Jana Odpovědná')
  await page.getByLabel('E-mail', { exact: true }).fill('spolek@example.test')
  await page.getByLabel('Telefon', { exact: true }).fill('+420 777 123 456')
  await page.getByLabel('Kopie občanského průkazu odpovědné osoby', { exact: true }).setInputFiles('public/images/vysker-znak-app-192.png')
  await page.locator('input[name="consent"]').check()
  let requests = 0
  page.on('request', request => {
    if (request.url().endsWith('/api/v1/rentals') && request.method() === 'POST') requests++
  })
  await expect(page.getByRole('button', { name: 'Odeslat žádost' })).toBeDisabled()
  expect(await page.locator('#rental-start').evaluate((input: HTMLInputElement) => input.validity.valueMissing)).toBe(true)
  expect(requests).toBe(0)
  await page.locator('#rental-event-type').selectOption('standard')
  await page.locator(`#rental-calendar [data-date="${key}"]`).click()
  await expect(page.locator('#rental-selection-summary')).toContainText('250 Kč')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: 'target/rental-pricing-public-desktop.png', style: '.skip-link { visibility: hidden !important; }' })
  await page.locator('.rental-contact').screenshot({ path: 'target/rental-pricing-contact.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.locator('section[aria-labelledby="rental-calendar-title"]').screenshot({ path: 'target/rental-pricing-public-mobile.png', style: screenshotStyle })
  await page.goto('/admin/pronajmy/majetek')
  const mobileCard = page.locator('section.rental-asset-card').filter({ has: page.getByRole('heading', { name: assetName, exact: true }) })
  await expect(mobileCard).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await mobileCard.locator('.rental-asset-rates').screenshot({ path: 'target/rental-pricing-admin-mobile.png', style: screenshotStyle })
})
