CREATE TABLE issue_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL CHECK (char_length(description) BETWEEN 1 AND 5000),
    address TEXT CHECK (char_length(address) BETWEEN 1 AND 300),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    reporter_name TEXT CHECK (char_length(reporter_name) BETWEEN 1 AND 120),
    request_ip TEXT NOT NULL,
    created_at TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'reported' CHECK (status IN ('reported','in_progress','resolved')),
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    photo BYTEA,
    CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CHECK (address IS NOT NULL OR latitude IS NOT NULL)
);
CREATE INDEX issue_reports_public ON issue_reports(id DESC) WHERE hidden=FALSE;

