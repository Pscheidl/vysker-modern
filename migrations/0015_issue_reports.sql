-- Each recipient gets their own message and a restart-safe delivery lease.
CREATE TABLE report_mail_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES issue_reports(id),
    recipient TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT,
    attempts BIGINT NOT NULL DEFAULT 0,
    next_attempt_at BIGINT NOT NULL,
    locked_until BIGINT NOT NULL DEFAULT 0,
    lock_token TEXT,
    sent_at BIGINT,
    created_at BIGINT NOT NULL,
    UNIQUE(report_id,recipient)
);
CREATE INDEX report_mail_queue_pending ON report_mail_queue(next_attempt_at,locked_until)
    WHERE sent_at IS NULL;

