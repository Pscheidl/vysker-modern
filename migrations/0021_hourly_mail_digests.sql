-- Existing individual messages keep their bodies, keys and retry state.
-- Only requests still in publication_outbox enter the hourly digest path.
ALTER TABLE subscribers ADD COLUMN next_digest_at BIGINT NOT NULL DEFAULT 0;
ALTER TABLE mail_queue ADD COLUMN digest_cutoff BIGINT;
ALTER TABLE mail_queue ADD CONSTRAINT mail_queue_digest_document
    CHECK (digest_cutoff IS NULL OR purpose='document');
ALTER TABLE mail_queue ADD CONSTRAINT mail_queue_recipient UNIQUE (id,subscriber_id);
CREATE UNIQUE INDEX mail_queue_digest_slot
    ON mail_queue(subscriber_id,consent_id,digest_cutoff)
    WHERE digest_cutoff IS NOT NULL;

CREATE TABLE mail_publication_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail_id BIGINT NOT NULL,
    subscriber_id BIGINT NOT NULL REFERENCES subscribers(id) ON DELETE CASCADE,
    notice_id BIGINT REFERENCES notices(id) ON DELETE CASCADE,
    document_id BIGINT REFERENCES documents(id) ON DELETE CASCADE,
    suppressed BOOLEAN NOT NULL DEFAULT FALSE,
    FOREIGN KEY (mail_id,subscriber_id) REFERENCES mail_queue(id,subscriber_id) ON DELETE CASCADE,
    CHECK ((notice_id IS NOT NULL) <> (document_id IS NOT NULL)),
    UNIQUE (notice_id,subscriber_id),
    UNIQUE (document_id,subscriber_id)
);
CREATE INDEX mail_publication_items_message ON mail_publication_items(mail_id,id);
CREATE INDEX publication_outbox_due ON publication_outbox(created_at,id);
CREATE INDEX publication_outbox_recipient
    ON publication_outbox(subscriber_id,consent_id,created_at,id);
