CREATE FUNCTION reject_protected_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'protected record is immutable: %', TG_TABLE_NAME;
END;
$$;
CREATE TRIGGER audit_log_prevent_update BEFORE UPDATE ON audit_log FOR EACH ROW EXECUTE FUNCTION reject_protected_change();
CREATE TRIGGER audit_log_prevent_truncate BEFORE TRUNCATE ON audit_log FOR EACH STATEMENT EXECUTE FUNCTION reject_protected_change();
CREATE TRIGGER notices_preserve_record BEFORE DELETE ON notices FOR EACH ROW EXECUTE FUNCTION reject_protected_change();
CREATE TRIGGER notices_prevent_truncate BEFORE TRUNCATE ON notices FOR EACH STATEMENT EXECUTE FUNCTION reject_protected_change();
CREATE TRIGGER attachments_preserve_metadata BEFORE DELETE ON attachments FOR EACH ROW EXECUTE FUNCTION reject_protected_change();
CREATE TRIGGER attachments_prevent_truncate BEFORE TRUNCATE ON attachments FOR EACH STATEMENT EXECUTE FUNCTION reject_protected_change();
CREATE TRIGGER consent_notices_immutable BEFORE UPDATE ON consent_notices FOR EACH ROW EXECUTE FUNCTION reject_protected_change();
CREATE TRIGGER notice_events_no_update BEFORE UPDATE ON notice_events FOR EACH ROW EXECUTE FUNCTION reject_protected_change();
CREATE TRIGGER notice_events_no_truncate BEFORE TRUNCATE ON notice_events FOR EACH STATEMENT EXECUTE FUNCTION reject_protected_change();

CREATE FUNCTION protect_consent_evidence() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.subscriber_id IS DISTINCT FROM OLD.subscriber_id
        OR NEW.notice_fingerprint IS DISTINCT FROM OLD.notice_fingerprint
        OR NEW.requested_at IS DISTINCT FROM OLD.requested_at
        OR (OLD.confirmed_at IS NOT NULL AND NEW.confirmed_at IS DISTINCT FROM OLD.confirmed_at)
        OR (OLD.withdrawn_at IS NOT NULL AND NEW.withdrawn_at IS DISTINCT FROM OLD.withdrawn_at)
        OR (OLD.superseded_at IS NOT NULL AND NEW.superseded_at IS DISTINCT FROM OLD.superseded_at)
    THEN RAISE EXCEPTION 'consent evidence is immutable'; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER subscription_consents_preserve_evidence BEFORE UPDATE ON subscription_consents FOR EACH ROW EXECUTE FUNCTION protect_consent_evidence();

CREATE FUNCTION protect_audit_retention() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM privacy_maintenance WHERE id=1 AND OLD.occurred_at<audit_delete_before)
    THEN RAISE EXCEPTION 'audit log is append only during retention'; END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER audit_log_prevent_delete BEFORE DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION protect_audit_retention();

CREATE FUNCTION protect_notice_retention() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM privacy_maintenance p JOIN notices n ON n.id=OLD.notice_id
        WHERE p.id=1 AND OLD.occurred_at<p.notice_delete_before
        AND n.status IN ('archived','withdrawn') AND n.withdrawn_at<p.notice_delete_before
    ) THEN RAISE EXCEPTION 'publication evidence is protected during retention'; END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER notice_events_no_delete BEFORE DELETE ON notice_events FOR EACH ROW EXECUTE FUNCTION protect_notice_retention();
