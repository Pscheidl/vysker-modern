-- The reservation feature has not been deployed. Its complete schema and
-- administrator permissions are introduced together in this migration.
ALTER TABLE administrators
    ADD COLUMN is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN can_view_identity BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN can_manage_permissions BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN can_create_accounts BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN can_manage_mail_settings BOOLEAN NOT NULL DEFAULT FALSE;

-- Preserve the original administrator. Empty databases assign the first
-- account at creation under the application's write lock.
UPDATE administrators
SET is_primary=TRUE, can_view_identity=TRUE, can_manage_permissions=TRUE,
    can_create_accounts=TRUE, can_manage_mail_settings=TRUE
WHERE id=(SELECT min(id) FROM administrators);

-- Do not reactivate or promote a different existing account silently.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM administrators)
       AND NOT EXISTS (SELECT 1 FROM administrators WHERE active AND is_primary) THEN
        RAISE EXCEPTION 'První správce je neaktivní. Před migrací oprávnění je nutné účet bezpečně obnovit.';
    END IF;
END $$;

CREATE UNIQUE INDEX administrators_one_primary ON administrators(is_primary) WHERE is_primary;
ALTER TABLE administrators
    ADD CONSTRAINT primary_administrator_has_all_permissions
        CHECK (NOT is_primary OR (can_view_identity AND can_manage_permissions AND can_create_accounts AND can_manage_mail_settings)),
    ADD CONSTRAINT mail_settings_require_all_permissions
        CHECK (NOT can_manage_mail_settings OR (can_view_identity AND can_manage_permissions AND can_create_accounts));

CREATE TABLE rental_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    -- Current readers still support historical price fields and snapshots.
    weekday_price BIGINT NOT NULL CHECK (weekday_price >= 0),
    weekend_price BIGINT NOT NULL CHECK (weekend_price >= 0),
    hourly_price BIGINT CHECK (hourly_price BETWEEN 0 AND 10000000),
    weekend_day_price BIGINT CHECK (weekend_day_price BETWEEN 0 AND 10000000),
    notification_email TEXT NOT NULL,
    require_meter BOOLEAN NOT NULL DEFAULT TRUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE rental_asset_rates (
    asset_id BIGINT NOT NULL REFERENCES rental_assets(id) ON DELETE CASCADE,
    rate_group TEXT NOT NULL CHECK (rate_group IN ('local_person','local_organization','external')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    weekday_price BIGINT CHECK (weekday_price BETWEEN 0 AND 10000000),
    weekend_price BIGINT CHECK (weekend_price BETWEEN 0 AND 10000000),
    hourly_price BIGINT CHECK (hourly_price BETWEEN 0 AND 10000000),
    PRIMARY KEY (asset_id,rate_group)
);

CREATE TABLE rental_event_rates (
    asset_id BIGINT NOT NULL REFERENCES rental_assets(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL CHECK (event_type IN ('nonprofit','standard')),
    hourly_price BIGINT CHECK (hourly_price BETWEEN 0 AND 10000000),
    weekend_day_price BIGINT CHECK (weekend_day_price BETWEEN 0 AND 10000000),
    PRIMARY KEY (asset_id,event_type)
);

CREATE TABLE rental_series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES rental_assets(id),
    interval_days INTEGER CHECK (interval_days IN (7,14)),
    interval_months INTEGER CHECK (interval_months = 1),
    repeat_until DATE NOT NULL,
    created_by BIGINT NOT NULL REFERENCES administrators(id),
    created_at TEXT NOT NULL,
    CONSTRAINT rental_series_interval_choice CHECK (num_nonnulls(interval_days,interval_months) = 1)
);

CREATE TABLE rentals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES rental_assets(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    start_minute SMALLINT,
    end_minute SMALLINT,
    starts_local TIMESTAMP GENERATED ALWAYS AS (start_date + COALESCE(start_minute,0) * INTERVAL '1 minute') STORED,
    ends_local TIMESTAMP GENERATED ALWAYS AS (end_date + COALESCE(end_minute,1440) * INTERVAL '1 minute') STORED,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT NOT NULL,
    address TEXT NOT NULL,
    tenant_type TEXT NOT NULL DEFAULT 'person' CHECK (tenant_type IN ('person','organization')),
    organization_ico TEXT CHECK (organization_ico IS NULL OR organization_ico ~ '^[0-9]{8}$'),
    responsible_name TEXT CHECK (responsible_name IS NULL OR char_length(btrim(responsible_name)) BETWEEN 1 AND 120),
    is_local BOOLEAN NOT NULL DEFAULT FALSE,
    locality_source TEXT NOT NULL DEFAULT 'none' CHECK (locality_source IN ('none','manual','automatic')),
    rate_group TEXT NOT NULL DEFAULT 'external',
    rate_snapshot JSONB,
    event_type TEXT CHECK (event_type IN ('nonprofit','standard')),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','invoiced','paid','rejected','closed','cancelled')),
    rental_price BIGINT NOT NULL CHECK (rental_price >= 0),
    energy_kwh TEXT,
    energy_cost BIGINT,
    extra_cost BIGINT,
    total_price BIGINT,
    account_iban TEXT,
    account_number TEXT,
    bank_code TEXT,
    payment_iban TEXT,
    due_days INTEGER,
    invoice_issued_on DATE,
    invoice_due_on DATE,
    invoice_pdf_attached BOOLEAN,
    invoice_sent_at TEXT,
    billing_error TEXT,
    auto_invoice_retry_after BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    identity_consent_at TEXT,
    require_meter BOOLEAN NOT NULL,
    source TEXT NOT NULL DEFAULT 'public' CHECK (source IN ('public','admin')),
    wait_for_payment BOOLEAN NOT NULL DEFAULT TRUE,
    series_id BIGINT REFERENCES rental_series(id),
    last_reminder_date DATE,
    identity BYTEA,
    identity_type TEXT,
    before_photo BYTEA,
    before_type TEXT,
    before_photo_taken_at TEXT,
    after_photo BYTEA,
    after_type TEXT,
    after_photo_taken_at TEXT,
    CHECK (end_date >= start_date AND end_date - start_date < 28),
    CONSTRAINT rental_hours_valid CHECK (
        (start_minute IS NULL AND end_minute IS NULL) OR
        (start_minute IS NOT NULL AND end_minute IS NOT NULL AND start_date=end_date
         AND start_minute BETWEEN 0 AND 1380 AND end_minute BETWEEN 60 AND 1440
         AND start_minute%60=0 AND end_minute%60=0 AND end_minute>start_minute)
    ),
    CONSTRAINT rental_admin_options CHECK (source='admin' OR (wait_for_payment AND series_id IS NULL)),
    CONSTRAINT rentals_rate_group_check CHECK (rate_group IN ('local_person','local_organization','external','nonprofit','standard')),
    CONSTRAINT rental_declared_group CHECK (
        (event_type IS NOT NULL AND rate_group=event_type) OR
        (event_type IS NULL AND rate_group=CASE WHEN NOT is_local THEN 'external' WHEN tenant_type='organization' THEN 'local_organization' ELSE 'local_person' END)
    ),
    CONSTRAINT rental_organization_fields CHECK (
        tenant_type='organization' OR (organization_ico IS NULL AND responsible_name IS NULL)
    )
);
CREATE INDEX rental_period ON rentals(asset_id,starts_local,ends_local) WHERE status NOT IN ('rejected','cancelled');
CREATE INDEX rental_series_members ON rentals(series_id,start_date) WHERE series_id IS NOT NULL;

CREATE TABLE rental_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES rental_assets(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    start_minute SMALLINT,
    end_minute SMALLINT,
    starts_local TIMESTAMP GENERATED ALWAYS AS (start_date + COALESCE(start_minute,0) * INTERVAL '1 minute') STORED,
    ends_local TIMESTAMP GENERATED ALWAYS AS (end_date + COALESCE(end_minute,1440) * INTERVAL '1 minute') STORED,
    CHECK (end_date >= start_date),
    CONSTRAINT rental_block_hours_valid CHECK (
        (start_minute IS NULL AND end_minute IS NULL) OR
        (start_minute IS NOT NULL AND end_minute IS NOT NULL AND start_date=end_date
         AND start_minute BETWEEN 0 AND 1380 AND end_minute BETWEEN 60 AND 1440
         AND start_minute%60=0 AND end_minute%60=0 AND end_minute>start_minute)
    )
);
CREATE INDEX rental_blocks_by_asset_period ON rental_blocks(asset_id,start_date,end_date);

CREATE TABLE rental_access_tokens (
    rental_id BIGINT NOT NULL REFERENCES rentals(id) ON DELETE CASCADE,
    token_hash TEXT PRIMARY KEY
);

CREATE TABLE rental_mail_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id BIGINT NOT NULL REFERENCES rentals(id),
    recipient TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT,
    purpose TEXT NOT NULL,
    attempts BIGINT NOT NULL DEFAULT 0,
    next_attempt_at BIGINT NOT NULL,
    locked_until BIGINT NOT NULL DEFAULT 0,
    lock_token TEXT,
    sent_at BIGINT,
    cancelled_at BIGINT,
    created_at BIGINT NOT NULL,
    -- A supplied invoice PDF is retained only while its message awaits SMTP.
    invoice_attachment BYTEA,
    CONSTRAINT rental_invoice_attachment_check CHECK (invoice_attachment IS NULL OR
        (purpose = 'invoice' AND sent_at IS NULL AND cancelled_at IS NULL
         AND octet_length(invoice_attachment) <= 10485760))
);
CREATE INDEX rental_mail_pending ON rental_mail_queue(next_attempt_at,locked_until) WHERE sent_at IS NULL;

