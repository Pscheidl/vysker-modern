ALTER TABLE issue_reports
    ADD COLUMN resolution_comment TEXT CHECK (char_length(resolution_comment) BETWEEN 1 AND 5000),
    ADD COLUMN resolution_updated_at TEXT;

CREATE TABLE issue_report_resolution_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES issue_reports(id) ON DELETE CASCADE,
    photo BYTEA NOT NULL CHECK (octet_length(photo) BETWEEN 1 AND 15000000)
);
CREATE INDEX issue_report_resolution_photos_report ON issue_report_resolution_photos(report_id, id);
