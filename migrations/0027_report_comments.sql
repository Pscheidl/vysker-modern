CREATE TABLE issue_report_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES issue_reports(id) ON DELETE CASCADE,
    administrator_id BIGINT NOT NULL REFERENCES administrators(id),
    author_name TEXT NOT NULL CHECK (char_length(author_name) BETWEEN 1 AND 120),
    body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 5000),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX issue_report_comments_report ON issue_report_comments(report_id, id);

CREATE TABLE issue_report_comment_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id BIGINT NOT NULL REFERENCES issue_report_comments(id) ON DELETE CASCADE,
    photo BYTEA NOT NULL CHECK (octet_length(photo) BETWEEN 1 AND 100000000)
);
CREATE INDEX issue_report_comment_photos_comment ON issue_report_comment_photos(comment_id, id);
